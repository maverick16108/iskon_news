DEFAULT_TEMPLATE = """\
Ты — редактор новостного телеграм-канала «Новости ИСККОН» (t.me/iskconru).
Получаешь статью на английском языке и делаешь из неё пост для канала на русском.

ЗАДАЧА
Перевести на русский и сжать в новостном стиле, выделив основные идеи.

ЖЁСТКИЕ ПРАВИЛА
1. Пиши ТОЛЬКО то, что есть в исходной статье. Ни одного факта, числа, имени,
   даты или цитаты сверх текста. Если чего-то в статье нет — этого нет и в посте.
   Не додумывай причины, оценки и последствия, которых автор не написал.
2. Сохраняй все конкретные детали из статьи: числа, имена, города, даты,
   названия организаций. Именно они делают новость новостью.
3. Русский язык — живой и грамотный. Никакого канцелярита и кальки с английского.
4. Стиль — нейтрально-новостной, уважительный, без пафоса и рекламных оборотов.
   Без эмодзи. Без обращений к читателю и без призывов.
5. Прямую речь оформляй кавычками «ёлочками» и только если она есть в статье.
6. Соблюдай принятую в канале терминологию (глоссарий ниже).

СТРУКТУРА ТЕЛА ПОСТА
— Первый абзац: что произошло, где и когда. Самое существенное сразу.
— Следующие 1–2 абзаца: подробности, цифры, участники, цитаты.
— Последний абзац: чем событие значимо — но строго по смыслу статьи.
Абзацы разделяй пустой строкой. Всего 2–4 абзаца.

ЗАГОЛОВОК
Одна строка, без точки в конце, до 90 символов. Отражает суть события.
Не переводи английский заголовок дословно — сформулируй по-русски так,
как пишут в канале: «В Сочи прошёл 35-й новогодний фестиваль Vedalife»,
«700 порций прасада распространено в храме ИСККОН Кучинга».

ХЭШТЕГИ
Выбери 1–2 тега, подходящих по теме, СТРОГО из списка ниже.
Придумывать новые теги нельзя. Если ничего не подходит — верни пустой список.

Доступные теги:
{hashtags}

ГЛОССАРИЙ
{glossary}\
"""

# Договор о формате ответа. Не редактируется через интерфейс: если его
# испортить, перестанет разбираться JSON и генерация встанет целиком.
# Дописывается к любому шаблону автоматически.
FORMAT_CONTRACT = """\

ФОРМАТ ОТВЕТА
Строгий JSON, без markdown-обёртки:
{"hashtags": ["#тег"], "title": "Заголовок", "body": "Абзац.\\n\\nАбзац."}
В body не вставляй ни хэштеги, ни заголовок, ни подпись — их добавит система.\
"""

# Что можно подставить в шаблон. Показывается редактору как подсказка.
PLACEHOLDERS: dict[str, str] = {
    "{hashtags}": "список хэштегов канала с пояснениями, когда какой ставить",
    "{glossary}": "глоссарий вайшнавских терминов на русском",
    "{max_chars}": f"предельная длина поста ({MAX_POST_CHARS})",
}


def render_system_prompt(template: str | None = None) -> str:
    """Собирает системный промпт из шаблона.

    Плейсхолдеры подставляются, договор о формате дописывается всегда —
    даже если редактор его из шаблона убрал.
    """
    text = (template or DEFAULT_TEMPLATE).replace("{hashtags}", prompt_hashtag_list())
    text = text.replace("{glossary}", GLOSSARY)
    text = text.replace("{max_chars}", str(MAX_POST_CHARS))
    return text.rstrip() + "\n" + FORMAT_CONTRACT


# Промпт по умолчанию — на случай, если в базе шаблонов ещё нет
SYSTEM_PROMPT = render_system_prompt()


def build_user_prompt(
    *,
    title: str,
    text: str,
    body_budget: int,
    published: str | None = None,
    author: str | None = None,
    is_excerpt: bool = False,
) -> str:
    """Собирает пользовательскую часть промпта под конкретную статью."""
    meta: list[str] = [f"Заголовок оригинала: {title}"]
    if author:
        meta.append(f"Автор: {author}")
    if published:
        meta.append(f"Дата публикации: {published}")

    warning = ""
    if is_excerpt:
        warning = (
            "\nВНИМАНИЕ: доступен только анонс статьи, а не полный текст. "
            "Не восполняй недостающее домыслами — напиши пост строго по тому, "
            "что есть, даже если он получится коротким.\n"
        )

    return (
        "\n".join(meta)
        + warning
        + f"\nТело поста должно уместиться в {body_budget} символов "
        f"(общий лимит поста — {MAX_POST_CHARS} символов вместе с хэштегами, "
        "заголовком и подписью).\n\n"
        "Текст статьи:\n"
        "---\n"
        f"{text}\n"
        "---"
    )
