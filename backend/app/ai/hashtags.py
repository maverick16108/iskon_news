ALLOWED_HASHTAGS: frozenset[str] = frozenset(NEWS_HASHTAGS)


def prompt_hashtag_list() -> str:
    """Список тегов с пояснениями — вставляется в системный промпт."""
    return "\n".join(f"{tag} — {hint}" for tag, hint in NEWS_HASHTAGS.items())


def sanitize_hashtags(raw: str | list[str]) -> list[str]:
    """Отбрасывает всё, чего нет в списке канала."""
    if isinstance(raw, str):
        parts = raw.replace(",", " ").split()
    else:
        parts = list(raw)

    out: list[str] = []
    for part in parts:
        tag = part.strip().lower()
        if not tag:
            continue
        if not tag.startswith("#"):
            tag = "#" + tag
        if tag in ALLOWED_HASHTAGS and tag not in out:
            out.append(tag)
    return out
